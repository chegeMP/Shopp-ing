export function getLowestPrice(product: Product): ProductPrice {
  return product.prices.reduce((min, p) => (p.price < min.price ? p : min));
}

export function getHighestPrice(product: Product): ProductPrice {
  return product.prices.reduce((max, p) => (p.price > max.price ? p : max));
}

export function getSavings(product: Product): number {
  const low = getLowestPrice(product).price;
  const high = getHighestPrice(product).price;
  return high - low;
}

export function getSavingsPercentage(product: Product): number {
  const high = getHighestPrice(product).price;
  const savings = getSavings(product);
  return Math.round((savings / high) * 100);
}
